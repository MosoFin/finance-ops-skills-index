def main() -> int:
    data = load_index()
    conn_meta = yaml.safe_load(CONNECTORS.read_text())
    meta = {
        **data["meta"],
        "stages": data["stages"],
        "connectors": conn_meta["connectors"],
        "statuses": conn_meta["statuses"],
    }

    unknown = {
        sys_
        for s in data["skills"]
        for sys_ in (s.get("systems") or [])
        if sys_ not in conn_meta["connectors"]
    }
    if unknown:
        print(f"systems with no entry in connectors.yml: {sorted(unknown)}", file=sys.stderr)
        return 1
    ids = [s["id"] for s in data["skills"]]
    if len(ids) != len(set(ids)):
        dupes = {i for i in ids if ids.count(i) > 1}
        print(f"duplicate skill ids: {sorted(dupes)}", file=sys.stderr)
        return 1

    (ROOT / "README.md").write_text(index_page(data, conn_meta))
    (ROOT / "docs" / "CONNECTOR-TRACKER.md").write_text(tracker_page(conn_meta))

    (ROOT / "connectors").mkdir(exist_ok=True)
    (ROOT / "connectors" / "README.md").write_text(
        connectors_index(conn_meta, data["skills"])
    )
    n_conn = 0
    for cid, c in conn_meta["connectors"].items():
        if cid in NOT_A_SOURCE:
            continue
        d = ROOT / "connectors" / cid
        d.mkdir(parents=True, exist_ok=True)
        (d / "README.md").write_text(
            connector_page(cid, c, conn_meta, data["skills"], meta["stages"])
        )
        n_conn += 1
    for skill in data["skills"]:
        d = ROOT / "skills" / skill["id"]
        d.mkdir(parents=True, exist_ok=True)
        (d / "README.md").write_text(skill_page(skill, meta))

    import build_plugin
    n_plugin = build_plugin.build(
        ROOT, data["skills"], conn_meta["connectors"], conn_meta["statuses"], primary_system,
        meta["regrade_after_days"],
        yaml.safe_load((DATA / "goals.yml").read_text())["goals"], meta["stages"],
    )

    print(
        f"built README.md, {len(data['skills'])} skill pages, {n_conn} connector pages, "
        f"plugin with {n_plugin} vendor references"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
