# Formats a user hands over, not systems we connect to.
FILE_FORMATS = {"csv", "pdf", "word", "powerpoint", "images", "any", "excel"}
AGNOSTIC = "_any"


def primary_system(skill: dict) -> str:
    real = [x for x in (skill.get("systems") or []) if x not in FILE_FORMATS]
    return real[0] if real else AGNOSTIC


def known_tiers() -> set[str]:
    """Badges defined in docs/TRUST-TIERS.md, so none can be invented in passing."""
    import re as _re
    text = (ROOT / "docs" / "TRUST-TIERS.md").read_text()
    return set(_re.findall(r"^\| `([A-Z][A-Z-]+)` \|", text, _re.M))


def load_index() -> dict:
    """Skills live under the data source they read: data/sources/<system>/<id>.yml."""
    meta = yaml.safe_load((DATA / "meta.yml").read_text())
    skills, misfiled = [], []
    for f in sorted((DATA / "sources").glob("*/*.yml")):
        sk = yaml.safe_load(f.read_text())
        if f.parent.name != primary_system(sk):
            misfiled.append(f"{f.relative_to(ROOT)} -> belongs in {primary_system(sk)}/")
        skills.append(sk)
    if misfiled:
        raise SystemExit("skills filed under the wrong data source:\n  " + "\n  ".join(misfiled))

    outward = [
        sk["id"] for sk in skills
        if "CLIENT-FACING" in (sk.get("tiers") or [])
        and not {"NO-AUTO-SEND", "SENDS-EXTERNALLY"} & set(sk.get("tiers") or [])
    ]
    if outward:
        raise SystemExit(
            "CLIENT-FACING without a send declaration: " + ", ".join(outward)
            + "\nA reader must never have to guess whether output leaves the building."
        )

    defined = known_tiers()
    unknown = sorted(
        {t for sk in skills for t in (sk.get("tiers") or [])} - defined
    )
    if unknown:
        raise SystemExit(
            "badges not defined in docs/TRUST-TIERS.md: " + ", ".join(unknown)
            + "\nA badge is a claim readers rely on — define it before using it."
        )
    return {**meta, "skills": skills}
def esc(v) -> str:
    """Escape angle brackets so placeholders like <YYYY-MM> survive Markdown."""
    return str(v).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


