        if org and org not in ("none-found", "none"):
            L += [f"[`{org}`](https://github.com/{org}) on GitHub publishes no skills or MCP server "
                  f"for agents as of {c.get('skills_checked', '—')}. That is a dated fact, not a permanent one.", ""]

